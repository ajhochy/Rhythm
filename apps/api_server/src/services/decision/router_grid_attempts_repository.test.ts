it('repair-c3: SQLite restart keeps first classification and latest applied model without diagnostic log', async () => {
  const path = join(mkdtempSync(join(tmpdir(), 'grid-attempts-')), 'ledger.db');
  let db = new Database(path); db.pragma('journal_mode = MEMORY'); runMigrations(db); const prev = setDb(db);
  try {
    const modulePath = './router_grid_attempts_repository';
    const mod = await import(modulePath).catch(() => null);
    expect(mod, 'durable repository must exist').not.toBeNull();
    const repo = new mod.RouterGridAttemptsRepository();
    const classification = { tier: 4, category: 'knowledge', canQueue: false, securitySensitive: false, estInputTokens: 12, source: 'rules', reason: 'ok' };
    const result = { model: 'openai/fake', provider: 'openai', effortRequested: 'high', effortApplied: 'high', accountId: 'a', accountSource: 'router', tierUsed: 4, kind: 'route', reason: 'ok', degraded: false, applied: true, trace: [] };
    await repo.append('fake-session', classification, result);
    await repo.append('fake-session', { ...classification, tier: 1 }, { ...result, model: 'anthropic/fake', provider: 'anthropic' });
    await repo.append('fake-session', classification, { ...result, kind: 'shadow', model: 'openai/shadow' });
    await repo.append('fake-session', classification, { ...result, kind: 'none', model: null, provider: null, tierUsed: null, reason: 'no_usable_route' });
    db.close(); db = new Database(path); setDb(db);
    expect(await new mod.RouterGridAttemptsRepository().readState('fake-session')).toEqual({ classification, model: 'anthropic/fake', provider: 'anthropic', accountId: 'a', accountSource: 'router' });
    const stored = db.prepare('SELECT classification_json,result_json FROM agent_router_grid_attempts ORDER BY id').all();
    expect(stored).toHaveLength(4);
    expect(Object.keys(JSON.parse((stored[0] as any).classification_json)).sort()).toEqual(['canQueue', 'category', 'estInputTokens', 'reason', 'securitySensitive', 'source', 'tier']);
    expect(Object.keys(JSON.parse((stored[0] as any).result_json)).sort()).toEqual(['accountId', 'accountSource', 'applied', 'degraded', 'effortApplied', 'effortRequested', 'kind', 'model', 'provider', 'reason', 'tierUsed', 'trace']);
    expect(db.prepare('SELECT COUNT(*) AS n FROM agent_decision_log').get()).toEqual({ n: 0 });
  } finally { setDb(prev); db.close(); } // Fixtures intentionally preserved.
});
it('pending failed route cannot supersede a prior explicit-pin applied receipt', async () => {
  const db = new Database(':memory:'); runMigrations(db); const previous = setDb(db);
  try {
    const repo = new RouterGridAttemptsRepository();
    await repo.append('pin-session', c, { ...r, accountSource: 'pinned', applied: true });
    await repo.append('pin-session', c, { ...r, accountSource: 'router', accountId: 'other', applied: false });
    expect(await repo.readState('pin-session')).toMatchObject({ accountSource: 'pinned', accountId: 'a' });
    expect(await repo.isRouterOwnedAccount('pin-session', 'openai', 'other')).toBe(false);
  } finally { setDb(previous); db.close(); }
});

it('legacy route without applied is ambiguous and never authorizes restart auto ownership', async () => {
  const db = new Database(':memory:'); runMigrations(db); const previous = setDb(db);
  try {
    db.prepare('INSERT INTO agent_router_grid_attempts(session_id,created_at,classification_json,result_json) VALUES (?,?,?,?)')
      .run('legacy-session', new Date().toISOString(), JSON.stringify(c), JSON.stringify((({ applied: _applied, ...legacy }) => legacy)(r)));
    const repo = new RouterGridAttemptsRepository();
    expect(await repo.readState('legacy-session')).toBeNull();
    expect(await repo.isRouterOwnedAccount('legacy-session', 'openai', 'a')).toBe(false);
  } finally { setDb(previous); db.close(); }
});
