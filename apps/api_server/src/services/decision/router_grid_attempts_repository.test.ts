import { RouterGridAttemptsRepository } from './router_grid_attempts_repository';
import { recordDecision } from './decision_log';
import { runMigrations } from '../../database/migrations';
import { setDb } from '../../database/db';
const c = { tier: 4, category: 'knowledge', canQueue: false, securitySensitive: false, estInputTokens: 12, source: 'rules', reason: 'ok' };
const r = { model: 'openai/fake', provider: 'openai', effortRequested: 'high', effortApplied: 'high', accountId: 'a', accountSource: 'router', tierUsed: 4, kind: 'route', reason: 'ok', degraded: false, applied: true, trace: [] };
it('repair-c3: PG bootstrap schema and actual parameterized pool query boundary preserve restart state', async () => {
  const rows: any[] = [];
  const pool = { query: vi.fn(async (sql: string, values?: any[]) => {
    if (sql.startsWith('INSERT INTO agent_router_grid_attempts')) {
      expect(sql).toContain('VALUES ($1,$2,$3,$4)');
      rows.push({ classification_json: values![2], result_json: values![3] });
    }
    return { rows: sql.startsWith('SELECT classification_json') ? rows : [], rowCount: 0 };
  }) };
  const connectedPool = { ...pool, connect: async () => ({ query: pool.query, release: () => undefined }) };
  await runPostgresBootstrap(connectedPool as any);
  const schema = pool.query.mock.calls[0][0];
  expect(schema).toContain('CREATE TABLE IF NOT EXISTS agent_router_grid_attempts');
  expect(schema).toContain('GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
  expect(schema).toContain('ON agent_router_grid_attempts(session_id,id)');
  expect(schema).not.toMatch(/DROP|DELETE|query_preview/);
  const previous = env.dbClient; env.dbClient = 'postgres';
  const spy = vi.spyOn(database, 'getPostgresPool').mockReturnValue(pool as any);
  try {
    recordDecision({ feature: 'model_routing', mode: 'on', sessionId: 'pg-session', status: 'ok', applied: true });
    await new RouterGridAttemptsRepository().append('pg-session', c, r);
    await new RouterGridAttemptsRepository().append('pg-session', { ...c, tier: 1 }, { ...r, model: 'openai/next' });
    expect(await new RouterGridAttemptsRepository().readState('pg-session')).toEqual({ classification: c, model: 'openai/next', provider: 'openai', accountId: 'a', accountSource: 'router' });
    expect(pool.query.mock.calls.at(-1)).toEqual(['SELECT classification_json,result_json FROM agent_router_grid_attempts WHERE session_id=$1 ORDER BY id', ['pg-session']]);
  } finally { spy.mockRestore(); env.dbClient = previous; }
});
it('repair-c3: closed validation rejects prompt/error/secret fields and malformed values without mutation', async () => {
  const db = new Database(':memory:'); runMigrations(db); const previous = setDb(db);
  try {
    const repo = new RouterGridAttemptsRepository();
    for (const invalid of [{ ...c, query: 'private prompt' }, { ...c, tier: 9 }, { ...c, reason: 'provider body secret' }, { ...c, securitySensitive: null }]) {
      await expect(repo.append('s', invalid, r)).rejects.toThrow('invalid_grid_attempt');
    }
    for (const invalid of [{ ...r, error: 'secret' }, { ...r, effortApplied: 'unknown' }, { ...r, provider: 'other' },
      { ...r, trace: [{ action: 'route', tier: 4, excerpt: 'private' }] }]) await expect(repo.append('s', c, invalid)).rejects.toThrow('invalid_grid_attempt');
    expect(db.prepare('SELECT COUNT(*) AS n FROM agent_router_grid_attempts').get()).toEqual({ n: 0 });
  } finally { setDb(previous); db.close(); }
});
