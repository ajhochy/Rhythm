const GOOGLE_DESKTOP_CLIENT_ID_PATTERN = /^\d+-[A-Za-z0-9_-]+\.apps\.googleusercontent\.com$/;

/**
 * Normal packages must embed an already-authorized public desktop OAuth client ID.
 * CI provides it; local package wrappers must explicitly allowlist the same input.
 */
export function resolveRequiredGoogleDesktopClientId(env = process.env) {
  const configuredValue = env?.GOOGLE_DESKTOP_CLIENT_ID;
  const clientId = typeof configuredValue === 'string' ? configuredValue.trim() : '';
  if (!clientId) {
    throw new Error('GOOGLE_DESKTOP_CLIENT_ID is required for normal package builds. CI supplies the public desktop OAuth client ID; local package wrappers must explicitly allowlist it.');
  }
  if (!GOOGLE_DESKTOP_CLIENT_ID_PATTERN.test(clientId)) {
    throw new Error('GOOGLE_DESKTOP_CLIENT_ID must be a valid public desktop OAuth client ID ending in .apps.googleusercontent.com.');
  }
  return clientId;
}

/** Generates the non-secret configuration copied into the packaged application. */
export function renderPackagedBuildConfig(googleDesktopClientId) {
  return [
    '// Generated by package-mac.mjs. The OAuth client ID is public; no client secret is embedded.',
    `export const GOOGLE_DESKTOP_CLIENT_ID = ${JSON.stringify(googleDesktopClientId)};`,
    "export const RHYTHM_AUTH_API_BASE = 'https://api.vcrcapps.com';",
    '',
  ].join('\n');
}
