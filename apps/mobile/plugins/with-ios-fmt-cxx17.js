const fs = require('node:fs/promises');
const path = require('node:path');

const { withDangerousMod } = require('@expo/config-plugins');

const PATCH_MARKER = '# @generated by with-ios-fmt-cxx17';

function patchPodfile(podfile) {
  if (podfile.includes(PATCH_MARKER)) {
    return podfile;
  }

  const postInstallStart = podfile.indexOf('    react_native_post_install(');
  const postInstallEnd = podfile.indexOf('\n    )', postInstallStart);
  if (postInstallStart === -1 || postInstallEnd === -1) {
    throw new Error(
      'Unable to apply the iOS fmt C++17 compatibility setting: Expo Podfile template changed.',
    );
  }

  const insertionPoint = postInstallEnd + '\n    )'.length;
  const compatibilitySetting = `

    ${PATCH_MARKER}
    installer.pods_project.targets.each do |target|
      next unless target.name == 'fmt'

      target.build_configurations.each do |build_configuration|
        build_configuration.build_settings['CLANG_CXX_LANGUAGE_STANDARD'] = 'c++17'
      end
    end`;

  return (
    podfile.slice(0, insertionPoint) +
    compatibilitySetting +
    podfile.slice(insertionPoint)
  );
}

/**
 * Xcode 26.5 rejects fmt 11.0.2's C++20 consteval parser when React Native is
 * built from source. The legacy architecture requires that source build, so
 * constrain only the generated fmt pod target to C++17.
 */
module.exports = function withIosFmtCxx17(config) {
  return withDangerousMod(config, [
    'ios',
    async (modConfig) => {
      const podfilePath = path.join(
        modConfig.modRequest.platformProjectRoot,
        'Podfile',
      );
      let podfile = await fs.readFile(podfilePath, 'utf8');

      podfile = patchPodfile(podfile);
      await fs.writeFile(podfilePath, podfile);

      return modConfig;
    },
  ]);
};

module.exports.patchPodfile = patchPodfile;
